class IgVpCentileResult {
  final int lowerPoint;
  final String label;
  final List<double> row;
  const IgVpCentileResult({
    required this.lowerPoint,
    required this.label,
    required this.row,
  });
}

/// Same rules as web classifyVeryPretermCentile.
IgVpCentileResult? classifyVeryPretermCentile(
  double weightKg,
  int? weeks,
  int? days,
  String? sex,
) {
  if (!weightKg.isFinite || weightKg <= 0) return null;
  if (sex != 'Male' && sex != 'Female') return null;
  if (weeks == null || days == null) return null;
  if (weeks < igVpMinWeeks || weeks > igVpMaxWeeks) return null;
  if (weeks == igVpMaxWeeks && days > 6) return null;
  if (days < 0 || days > 6) return null;

  final idx = (weeks - igVpMinWeeks) * 7 + days;
  final table = sex == 'Male' ? igVpBoysKg : igVpGirlsKg;
  if (idx < 0 || idx >= table.length) return null;
  final row = table[idx];

  if (weightKg < row[0]) {
    return IgVpCentileResult(lowerPoint: 0, label: '<3rd centile', row: row);
  }
  for (var i = igVpCentilePoints.length - 1; i >= 0; i--) {
    if (weightKg >= row[i]) {
      final isLast = i == igVpCentilePoints.length - 1;
      final label = isLast
          ? '>${igVpCentilePoints[i]}th centile'
          : '${igVpCentilePoints[i]}th–${igVpCentilePoints[i + 1]}th centile';
      return IgVpCentileResult(
        lowerPoint: igVpCentilePoints[i],
        label: label,
        row: row,
      );
    }
  }
  return IgVpCentileResult(lowerPoint: 0, label: '<3rd centile', row: row);
}
